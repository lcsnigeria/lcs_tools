<?php
namespace LCSNG\Tools\Payments\Gateways;

use LCSNG\Tools\Payments\GatewayAbstract;
use LCSNG\Tools\Requests\LCS_Requests;

/**
 * Class PAYSTACK
 * 
 * Paystack Payment Gateway Adapter.
 *
 * Implements standardized payment initialization and verification against Paystack's REST API
 * (`https://paystack.co`) while adhering to the application's USD-first payment architecture.
 *
 * ### Architectural Behavior:
 * - **Currency Normalization (Inbound):** Accepts payment amounts strictly in `USD` (major units)
 *   and automatically converts them to Nigerian Naira (`NGN`) in kobo (`int`) via {@see GatewayAbstract::buildRequestFields()}
 *   before sending the initialization payload to Paystack.
 * - **Currency Normalization (Outbound):** During verification, preserves the exact settled `NGN`
 *   amount and currency from Paystack while fault-tolerantly computing `amount_in_dollar` (`float|null`)
 *   via {@see GatewayAbstract::normalizeVerificationResponse()}. For Paystack, it is recalculated from NGN
 *   using the converter's cached/current rate, rather than a rate saved when checkout was initialized.
 *   Treat it as an estimate, not a reliable reconciliation value.
 * - **Dual Checkout Support:** Returns both `checkout_url` (`authorization_url`) for full-page redirects
 *   and `checkout_code` (`access_code`) for Paystack Inline JS popups simultaneously.
 * - **Non-Throwing Responses:** API, network, or verification failures are captured and returned inside
 *   standardized response arrays with `'status' => false` and a descriptive `'message'`.
 *
 * @package LCSNG\Tools\Payments\Gateways
 * @see     \LCSNG\Tools\Payments\GatewayAbstract
 * @see     \LCSNG\Tools\Payments\GatewayInterface
 */
final class PAYSTACK extends GatewayAbstract
{
    private string $secretKey;
    private string $ccApiKey;
    private string $baseUrl = 'https://api.paystack.co';
    
    /**
     * Mapping of endpoint actions to their respective API paths.
     */
    const ENDPOINT = [
        'initialize' => '/transaction/initialize',
        'verify' => '/transaction/verify/',
    ];

    /**
     * Initialize a new Paystack gateway instance.
     *
     * @param string $secretKey Paystack secret API key (`sk_test_...` for test mode, `sk_live_...` for live mode).
     *                          Never expose this key on the frontend.
     * @param string $ccApiKey  API key for `LCS_CurrencyConverter` (`exchangerate-api`) used to convert
     *                          USD amounts to NGN kobo on initialization and NGN back to USD on verification.
     */
    public function __construct($secretKey, $ccApiKey)
    {
        $this->secretKey = $secretKey;
        $this->ccApiKey = $ccApiKey;
    }

    /**
     * Initialize a new payment transaction on Paystack.
     *
     * Validates the unified USD input fields, converts the USD amount to NGN kobo, dispatches a `POST`
     * request to `/transaction/initialize`, and normalizes the result into a 19-key response array.
     * Backfills fields not echoed by Paystack (such as `amount`, `currency`, `email`, and `metadata`)
     * from the original `$fields` input.
     *
     * @param array{
     *     email: string,
     *     amount: float|int,
     *     currency: string,
     *     customer?: string|null,
     *     reference?: string|null,
     *     callback_url?: string|null,
     *     cancel_url?: string|null,
     *     payment_methods?: array<int, string>|null,
     *     metadata?: array<string, mixed>|null,
     *     plan_id?: string|null,
     *     checkout_mode?: 'hosted'|'embedded'|null,
     *     payment_mode?: 'payment'|'subscription'|null,
     *     subaccount?: string|null,
     *     expires_at?: int|string|null
     * } $fields Unified payment initialization parameters:
     *   - `email` (required): Customer's email address.
     *   - `amount` (required): Positive charge amount in `USD` (major units, e.g., `50.00`); Paystack's plan price takes precedence for subscriptions.
     *   - `currency` (required): Must be `'USD'` (automatically converted to `'NGN'` for Paystack).
     *   - `customer` (optional): Existing Paystack customer code (`CUS_...`), stored in `metadata.customer_code`.
     *   - `reference` (optional): Unique merchant transaction reference (auto-generated by Paystack if omitted).
     *   - `callback_url` (optional): URL Paystack redirects to after a payment attempt completes (success or failure).
     *   - `cancel_url` (optional): URL Paystack redirects to if the customer cancels checkout (`metadata.cancel_action`).
     *   - `payment_methods` (optional): Allowed Paystack channels (`['card', 'bank', 'ussd', 'qr', 'mobile_money', 'bank_transfer']`).
     *   - `metadata` (optional): Associative array of custom key-value data attached to the transaction.
     *   - `plan_id` (optional): Paystack plan code; required for subscriptions and sent as Paystack's `plan` field.
     *   - `checkout_mode` (optional): Accepted for interface parity (`'hosted'`|`'embedded'`); Paystack returns both URL and access code.
     *   - `payment_mode` (optional): Billing mode (`'payment'`|`'subscription'`); subscriptions require `plan_id`.
     *   - `subaccount` (optional): Paystack subaccount code (`ACCT_...`) for split settlements.
     *   - `expires_at` (optional): Expiration timestamp/string stored in `metadata.expires_at`.
     *
     * @return array{
     *     status: bool,
     *     payment_status: string|null,
     *     payment_id: string|null,
     *     reference: string|null,
     *     checkout_url: string|null,
     *     checkout_code: string|null,
     *     gateway: string,
     *     checkout_mode: string|null,
     *     payment_mode: string|null,
     *     message: string,
     *     amount: float|null,
     *     currency: string|null,
     *     email: string|null,
     *     customer_data: array<string, mixed>,
     *     payment_methods: array<int, string>,
     *     metadata: array<string, mixed>,
     *     created_at: string|null,
     *     expires_at: string|null,
     *     gateway_mode: 'live'|'test'|null
     * } Standardized 19-key initialization response:
     *   - `status`: `true` if Paystack created the checkout session, `false` on API/network failure.
     *   - `payment_status`: Always `null` at initialization on Paystack.
     *   - `payment_id`: Always `null` at initialization on Paystack.
     *   - `reference`: Transaction reference required for subsequent verification.
     *   - `checkout_url`: Paystack hosted checkout URL (`authorization_url`) for browser redirects.
     *   - `checkout_code`: Paystack inline popup token (`access_code`) for `PaystackPop.setup()`.
     *   - `gateway`: Always `'paystack'`.
     *   - `checkout_mode`: Echoed from `$fields['checkout_mode']` (defaults to `'hosted'`).
     *   - `payment_mode`: Echoed from `$fields['payment_mode']` (defaults to `'payment'`).
     *   - `message`: Paystack API status or error message.
     *   - `amount`: Requested amount in `USD` (`float`), backfilled from `$fields['amount']`.
     *   - `currency`: Uppercase currency code (`'USD'`), backfilled from `$fields['currency']`.
     *   - `email`: Customer email address, backfilled from `$fields['email']`.
     *   - `customer_data`: Customer details array (`id`, `email`) backfilled from `$fields`.
     *   - `payment_methods`: Enabled payment channels array backfilled from `$fields`.
     *   - `metadata`: Transaction metadata array backfilled from `$fields`.
     *   - `created_at`: ISO 8601 timestamp when initialization occurred.
     *   - `expires_at`: ISO 8601 expiration timestamp if provided in `$fields`, else `null`.
     *   - `gateway_mode`: Always `null` at initialization on Paystack (populated on verify).
     *
     * @throws \InvalidArgumentException If `$fields` fails validation (missing email/amount/currency, non-USD currency, missing subscription `plan_id`, or empty `$ccApiKey`).
     * @throws \Exception If USD-to-NGN currency conversion fails prior to calling Paystack.
     */
    public function initializePayment(array $fields): array
    {
        $payload  = $this->buildRequestFields('paystack', $fields, $this->ccApiKey);
        $response = $this->sendRequest('initialize', $payload);

        return $this->normalizeInitializationResponse('paystack', $response, $fields);
    }

    /**
     * Verify the status and settlement details of a Paystack transaction by its reference.
     *
     * Queries `GET /transaction/verify/{reference}` and normalizes the response into a 22-key array.
     * Never throws on invalid references, failed transactions, or currency converter outages—instead
     * returns `'status' => false` on lookup failure, or `'status' => true` with `'amount_in_dollar' => null`
     * if NGN-to-USD conversion fails after a successful Paystack lookup.
     *
     * **Important:** Require `$result['status'] === true && $result['payment_status'] === 'success'`
     * before fulfillment. Also ensure the reference belongs to the expected order and reconcile the
     * returned NGN amount/currency with the expected gateway charge; `amount_in_dollar` is only an estimate.
     *
     * @param string $reference Unique Paystack transaction reference returned during initialization.
     *
     * @return array{
     *     status: bool,
     *     payment_id: string|null,
     *     payment_status: 'success'|'failed'|'abandoned'|'pending'|'ongoing'|'processing'|'queued'|'reversed'|string|null,
     *     payment_methods: array<int, string>,
     *     checkout_status: 'complete'|string|null,
     *     checkout_url: string|null,
     *     checkout_code: string|null,
     *     amount: float|null,
     *     amount_in_dollar: float|null,
     *     currency: string|null,
     *     customer_data: array<string, mixed>,
     *     subscription_data: array<string, mixed>,
     *     metadata: array<string, mixed>,
     *     created_at: string|null,
     *     expires_at: string|null,
     *     paid_at: string|null,
     *     transaction_date: string|null,
     *     gateway_mode: 'live'|'test'|null,
     *     ip_address: string|null,
     *     log: array<string, mixed>,
     *     message: string,
     *     last_payment_error: string|null
     * } Standardized 22-key verification response:
     *   - `status`: `true` if Paystack's verification API call succeeded, `false` if lookup/network failed.
     *   - `payment_id`: Paystack's internal numeric transaction ID cast to `string`.
     *   - `payment_status`: Paystack transaction state (`'success'` indicates confirmed payment).
     *   - `payment_methods`: Single-element array containing the payment channel used (e.g., `['card']`, `['bank_transfer']`).
     *   - `checkout_status`: Mapped to `'complete'` when `payment_status === 'success'`, otherwise mirrors `payment_status`.
     *   - `checkout_url`: Always `null` on Paystack verification responses.
     *   - `checkout_code`: Always `null` on Paystack verification responses.
     *   - `amount`: Actual amount settled by Paystack in major currency units (`NGN`, converted from kobo).
     *   - `amount_in_dollar`: USD equivalent (`float`) converted from settled `NGN`, or `null` if FX conversion failed.
     *     For Paystack, it is recalculated from NGN using the converter's cached/current rate, rather than a rate saved when checkout was initialized.
     *     Treat it as an estimate, not a reliable reconciliation value.
     *   - `currency`: Uppercase 3-letter ISO code of the settled currency (`'NGN'`).
     *   - `customer_data`: Full Paystack customer object (`id`, `customer_code`, `email`, `first_name`, `last_name`, `phone`, etc.).
     *   - `subscription_data`: Attached `plan`, `plan_object`, and/or `subaccount` details if applicable, else `[]`.
     *   - `metadata`: Normalized associative array of metadata attached during initialization (converts empty string `""` to `[]`).
     *   - `created_at`: ISO 8601 timestamp when the transaction was initialized.
     *   - `expires_at`: ISO 8601 expiration timestamp extracted from `metadata.expires_at`, or `null`.
     *   - `paid_at`: ISO 8601 timestamp when payment succeeded, or `null` if unpaid.
     *   - `transaction_date`: ISO 8601 timestamp of the transaction record.
     *   - `gateway_mode`: Paystack environment domain (`'live'` or `'test'`).
     *   - `ip_address`: Customer's IP address recorded by Paystack during checkout.
     *   - `log`: Paystack checkout interaction audit history array.
     *   - `message`: Paystack `gateway_response` (e.g., `'Successful'`) or API error message.
     *   - `last_payment_error`: Gateway decline/failure reason if `payment_status !== 'success'`, otherwise `null`.
     */
    public function verifyPayment(string $reference): array
    {
        if (empty(trim($reference))) {
            return $this->normalizeVerificationResponse('paystack', [
                'status'  => false,
                'message' => 'Transaction reference is required for verification.',
            ], $this->ccApiKey);
        }

        $response = $this->sendRequest('verify', ['reference' => $reference]);

        return $this->normalizeVerificationResponse('paystack', $response, $this->ccApiKey);
    }

    /**
     * Send an authenticated request to the Paystack API via LCS_Requests.
     *
     * @param string $endpoint Endpoint key from self::ENDPOINT (`'initialize'` | `'verify'`) or a full URL.
     * @param array  $data     Request payload for POST, or `['reference' => '...']` for `'verify'`.
     * @return array Decoded JSON response array from Paystack.
     */
    private function sendRequest(string $endpoint, array $data = []): array
    {
        if (!isset(self::ENDPOINT[$endpoint]) && !str_starts_with($endpoint, 'http')) {
            throw new \InvalidArgumentException("Invalid Paystack endpoint key: {$endpoint}");
        }

        $url     = str_starts_with($endpoint, 'http') ? $endpoint : $this->baseUrl . self::ENDPOINT[$endpoint];
        $method  = 'POST';
        $payload = $data;

        if ($endpoint === 'verify') {
            $reference = trim((string) ($data['reference'] ?? ''));
            if ($reference === '') {
                throw new \InvalidArgumentException('Transaction reference is required for Paystack verify endpoint.');
            }
            $url    .= rawurlencode($reference);
            $method  = 'GET';
            $payload = null; // Prevents send_curl() from appending ?query_string to the verify path
        }

        $REQUESTS = new LCS_Requests(true);
        $response = $REQUESTS->send_curl($url, $payload, [
            'METHOD'  => $method,
            'API_KEY' => $this->secretKey, // Automatically sets Authorization: Bearer header
        ]);

        // 1. Handle transport/cURL-level failure
        if (!($response['success'] ?? false)) {
            return [
                'status'  => false,
                'message' => $response['error'] ?? 'Network error communicating with Paystack API.',
            ];
        }

        // 2. Return decoded JSON directly when valid
        if (is_array($response['json'])) {
            return $response['json'];
        }

        // 3. Fallback if server returned non-JSON body (e.g., 502/504 HTML gateway error)
        return [
            'status'  => false,
            'message' => "Invalid JSON response from Paystack (HTTP {$response['http_code']}).",
        ];
    }

}